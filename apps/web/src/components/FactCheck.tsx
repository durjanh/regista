import type { Engine, FactCheck } from "../api/types";
import { usePrefs } from "../lib/prefs";

export function FactCheckBadge({ fc }: { fc: FactCheck | undefined }) {
  if (!fc) return null;
  const bias = fc.bias_flags?.length ?? 0;
  if (fc.passed && !bias)
    return (
      <span className="pill accent" title={`${fc.checked_claims} claims verified against match data`}>
        ✓ Fact-checked · {fc.checked_claims}
      </span>
    );
  if (fc.passed && bias) return <span className="pill warn">✓ Facts · {bias} wording flag{bias > 1 ? "s" : ""}</span>;
  return <span className="pill danger">⚠ {fc.issues.length} issue{fc.issues.length === 1 ? "" : "s"}</span>;
}

export function EngineBadge({ engine, ms }: { engine: Engine | undefined; ms?: number }) {
  const { t } = usePrefs();
  if (!engine) return null;
  return (
    <span className="ai-badge" title={engine === "azure" ? "Generated by Azure OpenAI agents" : "Deterministic offline engine"}>
      ✦ {engine === "azure" ? t("engine.azure") : t("engine.offline")}
      {ms !== undefined ? <span className="faint"> · {Math.round(ms)} ms</span> : null}
    </span>
  );
}

/** Full fact-check panel, including the Fair Commentary guardrail. */
export function FactCheckPanel({ fc }: { fc: FactCheck }) {
  return (
    <div className="stack" style={{ gap: 10 }}>
      <div className="check">
        <span className={`mark ${fc.passed ? "ok" : "bad"}`}>{fc.passed ? "✓" : "!"}</span>
        <div>
          <strong>{fc.passed ? "Every claim traced to match data" : "Some claims could not be verified"}</strong>
          <div className="xs muted">{fc.checked_claims} numeric and factual claims checked against the event log</div>
        </div>
      </div>
      {fc.issues.map((iss, i) => (
        <div className="check" key={`i${i}`}>
          <span className="mark bad">✕</span>
          <div className="small">
            <div>“{iss.sentence}”</div>
            <div className="xs muted">{iss.problem}</div>
          </div>
        </div>
      ))}
      <div className="divider" />
      <div className="check">
        <span className={`mark ${fc.bias_flags.length ? "warn" : "ok"}`}>{fc.bias_flags.length ? "!" : "✓"}</span>
        <div>
          <strong>Fair commentary</strong>
          <div className="xs muted">
            Players are described by what the data shows they did, never by innate traits. Research on football commentary has found
            physical and cognitive descriptors applied unevenly; this guardrail checks for it.
          </div>
        </div>
      </div>
      {fc.bias_flags.map((b, i) => (
        <div className="check" key={`b${i}`}>
          <span className="mark warn">↺</span>
          <div className="small">
            <div>
              <s>{b.phrase}</s>
            </div>
            <div className="xs muted">Suggested: {b.suggestion}</div>
          </div>
        </div>
      ))}
    </div>
  );
}
