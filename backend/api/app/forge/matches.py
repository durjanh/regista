def resolve_plants(plants: list[dict], home_profile, away_profile) -> list[dict]:
    out = []
    for p in plants:
        p = dict(p)
        if p.get("position") and not p.get("player_id"):
            team = home_profile if p["side"] == "home" else away_profile
            wanted = {"LB": ("LB", "LWB"), "RB": ("RB", "RWB"), "ST": ("ST",)}.get(p["position"], (p["position"],))
            pl = next((x for x in team.squad if x.starter and x.position in wanted), None)
            if not pl:
                continue
            p["player_id"] = pl.player_id
        out.append(p)
    return out


def _find_player(squad: list, name: str) -> str | None:
    for p in squad:
        if p.name == name:
            return p.player_id
    return None


def _modelled_goals(ref: ReferenceData, result: dict) -> list[dict]:
    """Goals for a real score whose scorers the dataset doesn't record: minutes drawn from when international goals
    are really scored (a stable draw per match), no scorer named."""
    if not hasattr(ref, "_goal_minutes"):
        ref._goal_minutes = [g["minute"] for g in ref.goal_rows if g["minute"] and g["minute"] <= 90]
    key = f"{result['date']}|{result['home_team']}|{result['away_team']}"
    rng = random.Random(int(hashlib.sha256(key.encode()).hexdigest()[:12], 16))
    goals = [{"team": team, "scorer": None, "assist": None, "minute": rng.choice(ref._goal_minutes), "penalty": False, "own_goal": False}
             for team, n in ((result["home_team"], result["home_score"]), (result["away_team"], result["away_score"])) for _ in range(n)]
    goals.sort(key=lambda g: g["minute"])
    for i in range(1, len(goals)):                                                  # keep goals at least two minutes apart
        goals[i]["minute"] = min(90, max(goals[i]["minute"], goals[i - 1]["minute"] + 2))
    return goals


def build_real_match(date: str, home: str, away: str, seed: int | None = None, ref: ReferenceData | None = None,
                     plants: list[dict] | None = None, modelled_goals: bool = False) -> dict:
    """`modelled_goals`: when the dataset doesn't record every scorer, model the goals instead of refusing (the real
    score stands; minutes are drawn, nobody is named)."""
    ref = ref or reference()
    result = ref.find_result(date, home, away)
    if not result:
        raise MatchBuildError(f"No result for {home} v {away} on {date}")
    home, away = result["home_team"], result["away_team"]
    goals = ref.goals_for(result)
    modelled = False
    if len(goals) != result["home_score"] + result["away_score"]:
        if not modelled_goals:
            raise MatchBuildError("Goal records are incomplete for this match")
        goals, modelled = _modelled_goals(ref, result), True
    if any((g["minute"] or 0) > 100 for g in goals) or (date, home, away) in ref.shootouts:
        raise MatchBuildError("Extra-time matches are not supported yet")

    must = {home: [], away: []}
    for g in goals:
        if not g["scorer"]:
            continue
        if g["own_goal"]:
            must[away if g["team"] == home else home].append(g["scorer"])
        else:
            must[g["team"]].append(g["scorer"])
            if g["assist"]:
                must[g["team"]].append(g["assist"])

    neutral = result["neutral"]
    hp = ref.team_profile(home, date, away, home=True, neutral=neutral, must_include=list(dict.fromkeys(must[home])))
    ap = ref.team_profile(away, date, home, home=False, neutral=neutral, must_include=list(dict.fromkeys(must[away])))

    if modelled:
        # Nobody is named when the goals are modelled: a real player's name on a goal he didn't score would be invented.
        for tp in (hp, ap):
            for p in tp.squad:
                p.name, p.name_source = f"{tp.name} No. {p.shirt}", "placeholder"

    schedule = []
    for g in goals:
        side = "home" if g["team"] == home else "away"
        scoring = hp if side == "home" else ap
        conceding = ap if side == "home" else hp
        entry = {"minute": g["minute"] or 45, "side": side, "penalty": g["penalty"], "own_goal": g["own_goal"],
                 "scorer_name": g["scorer"], "assist_name": g["assist"]}
        if g["own_goal"]:
            entry["og_pid"] = _find_player(conceding.squad, g["scorer"])
            entry["og_name"] = g["scorer"]
        else:
            entry["scorer_pid"] = _find_player(scoring.squad, g["scorer"])
        if g["assist"]:
            entry["assist_pid"] = _find_player(scoring.squad, g["assist"])
        schedule.append(entry)

    seed = seed if seed is not None else sum(ord(c) for c in f"{date}{home}{away}")
    venue = venue_info(result["city"], result["country"])
    venue["acclimatised"] = [tp.team_id for tp in (hp, ap) if tp.name == result["country"]]
    if plants is None:
        plants = FEATURED_PLANTS.get((date, home, away), [])
    sim = MatchSimulator(hp, ap, seed=seed, neutral=neutral, goal_schedule=schedule,
                         altitude_m=venue.get("altitude_m"), acclimatised=tuple(venue["acclimatised"]),
                         plants=resolve_plants(plants, hp, ap))
    sim.run()
    match_id = f"{date}-{slug(home)}-{slug(away)}"
    elo_h, elo_a = ref.pre_elo.get((date, home, away), (hp.elo, ap.elo))
    meta = {
        "competition": result["tournament"],
        "season": date[:4],
        "matchweek": 0,
        "venue": f"{result['city']}, {result['country']}",
        "kickoff": date,
        "referee": "Not recorded",
        "headline_hint": _real_headline(result, [] if modelled else goals, elo_h, elo_a),
        "source": {
            "kind": "real_result",
            "disclosure": MODELLED_GOALS_DISCLOSURE if modelled else REAL_DISCLOSURE,
            "goals_modelled": modelled,
            "real": {
                "date": date, "tournament": result["tournament"], "city": result["city"], "country": result["country"],
                "neutral": neutral, "home_score": result["home_score"], "away_score": result["away_score"],
                # Only recorded goals are real facts: modelled ones stay out, so no narration cites them.
                "goals": [] if modelled else [{"minute": g["minute"], "team_id": slug(g["team"]), "scorer": g["scorer"], "penalty": g["penalty"],
                           "own_goal": g["own_goal"], **({"assist": g["assist"]} if g["assist"] else {})} for g in goals],
            },
            "dataset": DATASET,
        },
        "elo": {"home": round(elo_h), "away": round(elo_a)},
        "h2h": ref.h2h(home, away, before=date),
        "scenario_tags": _real_tags(result, [] if modelled else goals, elo_h, elo_a),
        "venue_info": venue,
    }
    doc = sim.payload(match_id, meta)
    doc["physical"] = physical.compute(doc)
    fs = doc["meta"]["final_score"]
    if (fs["home"], fs["away"]) != (result["home_score"], result["away_score"]):
        raise MatchBuildError(f"Rebuild drifted from the real score: {fs} vs {result['home_score']}-{result['away_score']}")
    return doc


def _real_tags(result: dict, goals: list[dict], elo_h: float, elo_a: float) -> list[str]:
    tags = []
    hs, as_ = result["home_score"], result["away_score"]
    winner_elo = elo_h if hs > as_ else elo_a if as_ > hs else None
    loser_elo = elo_a if hs > as_ else elo_h if as_ > hs else None
    if winner_elo is not None and loser_elo - winner_elo > 150:
        tags.append("upset")
    running = {"h": 0, "a": 0}
    trailed = set()
    for g in goals:
        if g["team"] == result["home_team"]:
            running["h"] += 1
        else:
            running["a"] += 1
        if running["h"] < running["a"]:
            trailed.add("h")
        if running["a"] < running["h"]:
            trailed.add("a")
    if ("h" in trailed and hs > as_) or ("a" in trailed and as_ > hs):
        tags.append("comeback")
    if goals and (goals[-1]["minute"] or 0) >= 85 and abs(hs - as_) <= 1:
        tags.append("late_drama")
    if "World Cup" in result["tournament"] and "qualification" not in result["tournament"]:
        tags.append("world_cup")
    return tags


def _real_headline(result: dict, goals: list[dict], elo_h: float, elo_a: float) -> str:
    tags = _real_tags(result, goals, elo_h, elo_a)
    if "upset" in tags:
        return "Giant-killing"
    if "comeback" in tags:
        return "The comeback"
    if "late_drama" in tags:
        return "Late drama"
    if result["home_score"] + result["away_score"] >= 5:
        return "Goal fest"
    return result["tournament"]


def build_what_if(home_id: str, away_id: str, as_of: str | None = None, scenario: str = "balanced",
                  intensity: float = 0.5, seed: int | None = None, neutral: bool = True,
                  home_formation: str | None = None, away_formation: str | None = None,
                  ref: ReferenceData | None = None, max_tries: int = 40, plants: list[dict] | None = None) -> dict:
    ref = ref or reference()
    home, away = ref.name_of(home_id), ref.name_of(away_id)
    as_of = as_of or ref.latest_date()
    hp = ref.team_profile(home, as_of, away, home=True, neutral=neutral, formation=home_formation)
    ap = ref.team_profile(away, as_of, home, home=False, neutral=neutral, formation=away_formation)
    lam_h, lam_a = ref.expected_goals(hp.elo, ap.elo, neutral)
    em = engine_goal_model(ref)
    dr = hp.elo - ap.elo + (0 if neutral else 100)
    eng_h = math.exp(em["home"][0] + em["home"][1] * dr)
    eng_a = math.exp(em["away"][0] + em["away"][1] * dr)
    bias = {"home": max(0.3, min(3.0, lam_h / eng_h)), "away": max(0.3, min(3.0, lam_a / eng_a))}
    underdog = "home" if hp.elo < ap.elo else "away"
    base = seed if seed is not None else random.randint(1, 9_999_999)
    doc = None
    for i in range(max_tries):
        s = base + i * 7919
        sim = MatchSimulator(hp, ap, seed=s, scenario=scenario, intensity=intensity, neutral=neutral, scoring_bias=bias,
                             plants=resolve_plants(plants or [], hp, ap))
        sim.run()
        doc = sim.payload(f"whatif-{home_id}-{away_id}-{s}", {
            "competition": "What-if (synthetic)", "season": as_of[:4],
            "matchweek": 0, "venue": "Neutral venue" if neutral else "Home", "kickoff": min(as_of, ref.results[-1]["date"]),
            "referee": "Not recorded", "headline_hint": SCENARIO_LABELS.get(scenario, "What-if"),
            "source": {"kind": "what_if", "disclosure": WHATIF_DISCLOSURE, "dataset": DATASET},
            "elo": {"home": round(hp.elo), "away": round(ap.elo)},
            "h2h": ref.h2h(home, away),
            "expected_goals_prior": {"home": round(lam_h, 2), "away": round(lam_a, 2)},
        })
        if scenario_satisfied(doc, underdog):
            doc["meta"]["truth"]["seed_search_tries"] = i + 1
            doc["physical"] = physical.compute(doc)
            return doc
    doc["meta"]["truth"]["seed_search_tries"] = max_tries
    doc["meta"]["truth"]["constraint_met"] = False
    doc["physical"] = physical.compute(doc)
    return doc


