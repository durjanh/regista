ENGINE_MODEL_PATH = REPO_ROOT / "data" / "reference" / "engine_goal_model.json"
_engine_model: dict | None = None


def engine_goal_model(ref: ReferenceData | None = None, n: int = 320) -> dict:
    """The engine's own goals-vs-Elo-gap curve, fitted on unbiased simulations of real fixtures (cached to disk).
    What-if matches are then corrected by real_model / engine_model, so scorelines follow the real goal model
    without double-counting the strength the engine already simulates."""
    global _engine_model
    if _engine_model is not None:
        return _engine_model
    if ENGINE_MODEL_PATH.exists():
        _engine_model = json.loads(ENGINE_MODEL_PATH.read_text())
        return _engine_model
    ref = ref or reference()
    rng = random.Random(2024)
    pool = [r for r in ref.results if r["date"] >= "2010-01-01" and r["tournament"] != "Friendly"
            and len(ref.elo_hist.get(r["home_team"], [])) > 30 and len(ref.elo_hist.get(r["away_team"], [])) > 30]
    rows = []
    for i, r in enumerate(rng.sample(pool, n)):
        hp = ref.team_profile(r["home_team"], r["date"], r["away_team"], home=True, neutral=r["neutral"])
        ap = ref.team_profile(r["away_team"], r["date"], r["home_team"], home=False, neutral=r["neutral"])
        res = MatchSimulator(hp, ap, seed=10_000 + i, neutral=r["neutral"]).run()
        dr = hp.elo - ap.elo + (0 if r["neutral"] else 100)
        rows.append((dr, res["score"]["home"], res["score"]["away"]))
    _engine_model = {"home": _fit_log_linear([(d, h) for d, h, _ in rows]), "away": _fit_log_linear([(d, a) for d, _, a in rows]), "n": n}
    ENGINE_MODEL_PATH.write_text(json.dumps(_engine_model))
    return _engine_model


def _fit_log_linear(points: list[tuple[float, int]]) -> tuple[float, float]:
    bins: dict[int, list[int]] = {}
    for d, g in points:
        bins.setdefault(int(round(max(-500, min(500, d)) / 100) * 100), []).append(g)
    xs, ys, ws = [], [], []
    min_n = 8 if any(len(gs) >= 8 and sum(gs) for gs in bins.values()) else 1   # small samples: use every non-empty bin
    for b, gs in bins.items():
        m = sum(gs) / len(gs)
        if len(gs) >= min_n and m > 0:
            xs.append(b)
            ys.append(math.log(m))
            ws.append(len(gs))
    if not ws:
        return 0.0, 0.0
    sw = sum(ws)
    mx = sum(w * x for w, x in zip(ws, xs)) / sw
    my = sum(w * y for w, y in zip(ws, ys)) / sw
    slope = sum(w * (x - mx) * (y - my) for w, x, y in zip(ws, xs, ys)) / max(1e-9, sum(w * (x - mx) ** 2 for w, x in zip(ws, xs)))
    return my - slope * mx, slope


